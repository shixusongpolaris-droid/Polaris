def main():
    lines = []
    def P(s=""):
        print(s)
        lines.append(s)

    P("# 事件与占用总表")
    P()
    P(f"- 生成：{datetime.now():%Y-%m-%d %H:%M:%S}")
    P("- 数据来源：用户报告 + 实测数据反推")
    P()
    P("---")
    P()
    P("## 表 A：确切事件点")
    P()
    P("空调事件**严格开关交替**（已核对）：开→关→开→关→开→关→开→关→开→关")
    P()
    P("| 时间 | 类别 | 事件 | 来源 |")
    P("|---|---|---|---|")
    for t, c, e, s in sorted(EVENTS):
        P(f"| {t} | {c} | {e} | {s} |")
    P()
    P("---")
    P()
    P("## 表 B：占用区间（含空调状态）")
    P()
    P("`活动水平`列用于解释雷达表现：**活动**（走动）时雷达 96~100%；")
    P("**静止**（静坐/睡眠）时雷达降至 26~55%。")
    P()
    P("| 起始 | 结束 | 人员状态 | 活动水平 | 空调 | 门/窗 | 依据 |")
    P("|---|---|---|---|---|---|---|")
    for a, b, st, act, ac, dw, why in INTERVALS:
        P(f"| {a} | {b} | **{st}** | {act} | {ac} | {dw} | {why} |")
    P()

    # 汇总
    P("---")
    P()
    P("## 汇总统计")
    P()
    tot = {}
    for a, b, st, act, ac, dw, why in INTERVALS:
        t1 = datetime.strptime(a, "%Y-%m-%d %H:%M")
        t2 = datetime.strptime(b, "%Y-%m-%d %H:%M")
        h = (t2 - t1).total_seconds() / 3600
        tot[st] = tot.get(st, 0) + h
    P("| 人员状态 | 累计时长 |")
    P("|---|---|")
    for st in sorted(tot, key=lambda k: -tot[k]):
        P(f"| {st} | {tot[st]:.1f} 小时 |")

    io.open(OUT_MD, "w", encoding="utf-8").write("\n".join(lines) + "\n")

    with io.open(OUT_EV, "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["time", "category", "event", "source"])
        for row in sorted(EVENTS):
            w.writerow(row)

    with io.open(OUT_IV, "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["start", "end", "occupancy", "activity", "ac_state",
                    "door_window", "basis"])
        for row in INTERVALS:
            w.writerow(row)

    print()
    print(f"输出: {OUT_MD}")
    print(f"输出: {OUT_EV}")
    print(f"输出: {OUT_IV}")
    return 0


