def set_run_font(run, cn=FONT_CN, size=10.5, bold=False):
    run.font.name = FONT_EN
    run.font.size = Pt(size)
    run.font.bold = bold
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), FONT_EN)
    rfonts.set(qn("w:hAnsi"), FONT_EN)
    rfonts.set(qn("w:eastAsia"), cn)


def para(doc, text="", size=10.5, bold=False, cn=FONT_CN,
         align=None, space_after=6, indent=True, line_spacing=1.5):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = line_spacing
    pf.left_indent = Cm(0)
    pf.right_indent = Cm(0)
    if indent:
        pf.first_line_indent = Pt(21)
    if text:
        r = p.add_run(text)
        set_run_font(r, cn=cn, size=size, bold=bold)
    return p


def heading(doc, text, size=13):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(16)
    pf.space_after = Pt(8)
    pf.line_spacing = 1.4
    r = p.add_run(text)
    set_run_font(r, cn=FONT_CN_HEAD, size=size, bold=True)
    return p


