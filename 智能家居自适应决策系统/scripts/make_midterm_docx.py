def build_txt():
    """纯文本版，模块之间用分隔线隔开，便于逐个复制。"""
    lines = ["中期报告填写材料",
             "基于强化学习与多目标优化的智能家居自适应决策系统",
             "（共五个模块，每个模块内容独立，可分别填入系统对应栏目）",
             ""]
    for title, paras in MODULES:
        lines.append("=" * 62)
        lines.append(title)
        lines.append("=" * 62)
        lines.append("")
        for t in paras:
            lines.append(t)
            lines.append("")
        lines.append("")
    text = "\n".join(lines)
    io.open(TXT_PATH, "w", encoding="utf-8").write(text)
    return text


